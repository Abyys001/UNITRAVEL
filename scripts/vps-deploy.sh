#!/usr/bin/env bash
# One-command deploy for a VPS whose host nginx owns 80/443 (docs/runbooks/deploy-vps-nginx.md).
#   scripts/vps-deploy.sh            first run: writes infra/.env.prod with fresh secrets, builds, starts, nginx + TLS
#   scripts/vps-deploy.sh            later runs (after git pull): rebuild + restart, secrets are kept
#   scripts/vps-deploy.sh nginx      only (re)write the nginx sites and certificates
#   scripts/vps-deploy.sh status     container state and smoke checks
# Host names come from the environment on the first run (defaults below) and from infra/.env.prod afterwards.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
ENV_FILE=infra/.env.prod
COMPOSE=(docker compose --env-file "$ENV_FILE" -f infra/compose.prod.yml -f infra/compose.vps.yml --profile mail-sink)

log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
hex() { openssl rand -hex "$1"; }

write_env() {
  [ -f "$ENV_FILE" ] && return 0
  log "Generating $ENV_FILE (secrets are created here, once)"
  local web=${WEB_HOST:-demo.unitravels.co.uk} admin=${ADMIN_HOST:-admin.unitravels.co.uk}
  local mobile=${MOBILE_HOST:-mobile.unitravels.co.uk} dev=${DEV_HOST:-dev.unitravels.co.uk}
  local pg=$(hex 24) rw=$(hex 24) ro=$(hex 24) tmp
  tmp=$(mktemp -d)
  openssl genpkey -algorithm ed25519 -out "$tmp/jwt.pem" 2>/dev/null
  local jwt_priv jwt_x
  jwt_priv=$(awk 'NF {printf "%s\\n", $0}' "$tmp/jwt.pem")
  jwt_x=$(openssl pkey -in "$tmp/jwt.pem" -pubout -outform DER | tail -c 32 | basenc --base64url | tr -d '=')
  rm -rf "$tmp"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/vps-deploy.sh on $(date -u +%F). Never commit. Back up the keys marked BACKUP elsewhere.
APP_ENV=staging
# ADR-0012: email-only sign-in on every surface. Testing phase only; set off before real data arrives.
TEST_SIGN_IN=on

# Three public hosts (+ the Developer Panel). The API and S3 uploads share them by path (infra/nginx/).
WEB_HOST=$web
ADMIN_HOST=$admin
DEV_HOST=$dev
MOBILE_HOST=$mobile
API_HOST=$mobile
STORAGE_HOST=$web
ACME_EMAIL=${ACME_EMAIL:-info@cybercina.co.uk}

POSTGRES_USER=unitravel
POSTGRES_PASSWORD=$pg
DATABASE_MIGRATE_URL=postgres://unitravel:$pg@postgres:5432/unitravel
DATABASE_URL=postgres://app_rw:$rw@postgres:5432/unitravel
DATABASE_RO_URL=postgres://app_ro:$ro@postgres:5432/unitravel

# BACKUP
JWT_PRIVATE_KEY='$jwt_priv'
JWT_PUBLIC_KEYS='[{"kty":"OKP","crv":"Ed25519","x":"$jwt_x","kid":"k1"}]'
# BACKUP
MASTER_ENCRYPTION_KEY=$(openssl rand -base64 32)
OTP_PEPPER=$(openssl rand -base64 32)

OBJECT_STORAGE_PUBLIC_ENDPOINT=https://$web
OBJECT_STORAGE_BUCKET=unitravel-documents
OBJECT_STORAGE_ACCESS_KEY=$(hex 16)
OBJECT_STORAGE_SECRET_KEY=$(hex 32)
# BACKUP
RUSTFS_SSE_S3_MASTER_KEY=$(openssl rand -base64 32)

# Mail goes to the bundled Mailpit sink (UI: http://127.0.0.1:\${MAILPIT_PORT}). Replace with a real relay for production.
SMTP_URL=smtp://mailpit:1025

# Loopback ports nginx proxies to.
WEB_PORT=3080
CONSOLE_PORT=3081
API_PORT=3082
MOBILE_PORT=3083
STORAGE_PORT=3084
MAILPIT_PORT=3085
EOF
  chmod 600 "$ENV_FILE"
}

load_env() { set -a; . "$ROOT/$ENV_FILE"; set +a; }

write_nginx() {
  load_env
  local site=/etc/nginx/sites-available/unitravel.conf
  log "Writing $site"
  export WEB_HOST ADMIN_HOST DEV_HOST MOBILE_HOST WEB_PORT CONSOLE_PORT API_PORT MOBILE_PORT STORAGE_PORT
  local vars='$WEB_HOST $ADMIN_HOST $DEV_HOST $MOBILE_HOST $WEB_PORT $CONSOLE_PORT $API_PORT $MOBILE_PORT $STORAGE_PORT'
  envsubst "$vars" < infra/nginx/unitravel.conf.template > "$site.tmp"
  install -m 644 infra/nginx/unitravel-proxy.conf /etc/nginx/snippets/unitravel-proxy.conf

  # Only hosts that resolve to this server can get a certificate; the rest are left out until DNS exists.
  local me hosts=() h
  me=$(curl -fsS4 --max-time 5 https://ifconfig.me || hostname -I | awk '{print $1}')
  for h in "$WEB_HOST" "$ADMIN_HOST" "$MOBILE_HOST" "$DEV_HOST"; do
    if getent ahostsv4 "$h" | awk '{print $1}' | grep -qx "$me"; then hosts+=("$h"); else log "SKIP $h: DNS does not point at $me yet"; fi
  done

  for h in "${hosts[@]}"; do
    [ -f "/etc/letsencrypt/live/$h/fullchain.pem" ] && continue
    log "Certificate for $h"
    certbot certonly --webroot -w /var/www/acme -d "$h" --non-interactive --agree-tos -m "$ACME_EMAIL" --keep-until-expiring
  done

  # Keep only server blocks whose certificate exists, so nginx always reloads cleanly.
  python3 - "$site.tmp" "$site" "${hosts[@]}" <<'PY'
import re, sys, os
src, dst, hosts = sys.argv[1], sys.argv[2], set(sys.argv[3:])
blocks = re.split(r'(?m)^(?=# --- host: )', open(src).read())
out = [b for b in blocks if not b.startswith('# --- host: ') or (b.split()[3] in hosts and os.path.exists(f"/etc/letsencrypt/live/{b.split()[3]}/fullchain.pem"))]
open(dst, 'w').write(''.join(out))
PY
  rm -f "$site.tmp"
  ln -sfn "$site" /etc/nginx/sites-enabled/unitravel.conf
  # Never leave a broken site enabled: it would block every later reload on a shared host.
  if ! nginx -t; then rm -f /etc/nginx/sites-enabled/unitravel.conf; echo "nginx config invalid; site disabled" >&2; return 1; fi
  systemctl reload nginx
}

status() {
  load_env
  "${COMPOSE[@]}" ps --format 'table {{.Service}}\t{{.State}}\t{{.Status}}'
  for u in "https://$MOBILE_HOST/health" "https://$WEB_HOST/en" "https://$ADMIN_HOST/" "https://$MOBILE_HOST/" "https://$MOBILE_HOST/app/" "https://$DEV_HOST/"; do
    printf '%-45s %s\n' "$u" "$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$u" || echo ERR)"
  done
}

case "${1:-deploy}" in
  nginx) write_nginx ;;
  status) status ;;
  deploy)
    command -v docker >/dev/null && command -v nginx >/dev/null && command -v certbot >/dev/null || { echo "needs docker, nginx, certbot" >&2; exit 1; }
    write_env
    log "Building images (first build takes a while: Next.js apps and the Flutter SDK)"
    "${COMPOSE[@]}" build
    log "Starting the stack"
    "${COMPOSE[@]}" up -d --remove-orphans
    write_nginx
    status ;;
  *) echo "usage: $0 [deploy|nginx|status]" >&2; exit 2 ;;
esac
