os.makedirs(base, exist_ok=True)
for lang in ('en', 'fa'):
    with open(os.path.join(base, f'app_{lang}.arb'), 'w', encoding='utf-8') as f:
        json.dump(arb(lang), f, ensure_ascii=False, indent=2)
        f.write('\n')
