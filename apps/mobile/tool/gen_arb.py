def arb(lang):
    out = {'@@locale': lang}
    for k, v in T.items():
        text = v[0] if lang == 'en' else v[1]
        out[k] = text
        if lang == 'en' and len(v) > 2:
            out['@' + k] = {'placeholders': {p: ({'type': t, 'format': 'decimalPattern'} if t == 'int' else {'type': t}) for p, t in v[2].items()}}
    return out

