const DICT: Record<Locale, Record<MsgKey, string>> = { en, fa }

export type T = (key: MsgKey, vars?: Record<string, string | number>) => string

export function useT(): T {
  const [locale] = useLocale()
  return (key, vars) => (DICT[locale][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? ""))
}
